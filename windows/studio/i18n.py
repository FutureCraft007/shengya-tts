def is_chinese(language: str) -> bool:
    return language == "zh-CN" or (language == "system" and (locale.getlocale()[0] or "").lower().startswith(("zh", "chinese")))


def translate(key: str, language: str) -> str:
    pair = MESSAGES.get(key)
    return pair[0 if is_chinese(language) else 1] if pair else key
